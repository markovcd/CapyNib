package io.github.markovcd.capynib.ui.theme

/** How strongly the ink (the text color) shows where it is not plain text; the one place these alphas are set. */
object Ink {
    /** A ticked checklist item, in the editor and on a card. */
    const val TICKED = 0.62f

    /** A rule across a note. */
    const val RULE = 0.12f

    /** A tag's pill on a card. */
    const val TAG = 0.08f

    /** The fill behind a recording, and behind a photo while it loads. */
    const val FILL = 0.07f
}
